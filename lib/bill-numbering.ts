/**
 * lib/bill-numbering.ts
 *
 * Client-safe pure functions for Vendor Bill auto-numbering,
 * zero-padding formatters, and collision avoidance utilities.
 * Free of database/Node imports so it can be safely imported
 * in both Client Components and Server Components.
 */

/**
 * Safely escapes characters for regular expression matching.
 */
export function escapeRegex(text: string): string {
  return text.replace(/[-[\]{}()*+?.,\\^$|#\s]/g, "\\$&");
}

/**
 * Formats a sequential vendor bill number with prefix and zero-padding.
 * Example: formatBillNumber("BILL-", 1, 4) -> "BILL-0001"
 * Example: formatBillNumber("BILL-", 42, 4) -> "BILL-0042"
 */
export function formatBillNumber(
  prefix: string = "BILL-",
  nextNumber: number = 1,
  padding: number = 4,
): string {
  const cleanPrefix = String(prefix ?? "BILL-");
  const cleanNum = Math.max(1, Number(nextNumber) || 1);
  const cleanPad = Math.max(1, Number(padding) || 4);
  const padded = String(cleanNum).padStart(cleanPad, "0");
  return `${cleanPrefix}${padded}`;
}

/**
 * Extracts the numeric sequence from a bill number if it starts with the prefix.
 * Example: extractBillNumberPart("BILL-0001", "BILL-") -> 1
 * Example: extractBillNumberPart("BILL-0042", "BILL-") -> 42
 * Example: extractBillNumberPart("INV-9999", "BILL-") -> null
 */
export function extractBillNumberPart(
  billNumber: string,
  prefix: string = "BILL-",
): number | null {
  const num = (billNumber || "").trim();
  const pfx = (prefix || "").trim();
  if (!num.toLowerCase().startsWith(pfx.toLowerCase())) return null;

  const remainder = num.slice(pfx.length);
  if (!/^\d+$/.test(remainder)) return null;

  const parsed = parseInt(remainder, 10);
  return isNaN(parsed) ? null : parsed;
}

/**
 * Checks whether a bill number conforms to the auto-generated pattern.
 * Example: isAutoGeneratedBillNumber("BILL-0001") -> true
 * Example: isAutoGeneratedBillNumber("INV-2026-01") -> false
 */
export function isAutoGeneratedBillNumber(
  billNumber: string,
  prefix: string = "BILL-",
): boolean {
  return extractBillNumberPart(billNumber, prefix) !== null;
}

/**
 * Parses user input for Next Bill Number (e.g. "0002" or 2).
 * Preserves the zero-padding length based on entered string.
 */
export function parseNextBillNumberInput(input: string | number): {
  nextNumber: number;
  padding: number;
  formattedString: string;
} {
  const str = String(input ?? "").trim();
  const digitsOnly = str.replace(/[^0-9]/g, "");

  if (!digitsOnly) {
    return {
      nextNumber: 1,
      padding: 4,
      formattedString: "0001",
    };
  }

  const numeric = parseInt(digitsOnly, 10) || 1;
  const padding = Math.max(1, digitsOnly.length);
  const formattedString = String(numeric).padStart(padding, "0");

  return {
    nextNumber: numeric,
    padding,
    formattedString,
  };
}

/**
 * Finds the next available non-colliding bill number starting from `startingNumber`.
 * Guaranteed to never produce duplicates against existing records.
 */
export function findNextAvailableBillNumber(
  prefix: string = "BILL-",
  startingNumber: number = 1,
  padding: number = 4,
  existingNumbers: Set<string>,
): {
  billNumber: string;
  allocatedNumber: number;
} {
  let candidate = Math.max(1, startingNumber);
  const cleanPrefix = String(prefix ?? "BILL-");
  const cleanPad = Math.max(1, Number(padding) || 4);

  // Normalize existing set keys to lowercase for case-insensitive collision check
  const normalizedSet = new Set<string>();
  for (const item of existingNumbers) {
    if (typeof item === "string") {
      normalizedSet.add(item.trim().toLowerCase());
    }
  }

  while (true) {
    const formatted = `${cleanPrefix}${String(candidate).padStart(cleanPad, "0")}`;
    if (!normalizedSet.has(formatted.toLowerCase())) {
      return {
        billNumber: formatted,
        allocatedNumber: candidate,
      };
    }
    candidate++;
  }
}
