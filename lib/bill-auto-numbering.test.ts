import { describe, expect, it } from "vitest";
import {
  escapeRegex,
  extractBillNumberPart,
  findNextAvailableBillNumber,
  formatBillNumber,
  isAutoGeneratedBillNumber,
  parseNextBillNumberInput,
} from "./bill-numbering";

describe("Vendor Bill Auto-Numbering System", () => {
  describe("formatBillNumber", () => {
    it("formats sequential bill numbers with default BILL- prefix and 4-digit padding", () => {
      expect(formatBillNumber("BILL-", 1, 4)).toBe("BILL-0001");
      expect(formatBillNumber("BILL-", 2, 4)).toBe("BILL-0002");
      expect(formatBillNumber("BILL-", 3, 4)).toBe("BILL-0003");
      expect(formatBillNumber("BILL-", 42, 4)).toBe("BILL-0042");
      expect(formatBillNumber("BILL-", 999, 4)).toBe("BILL-0999");
      expect(formatBillNumber("BILL-", 1000, 4)).toBe("BILL-1000");
    });

    it("handles numbers exceeding the zero-padding length gracefully", () => {
      expect(formatBillNumber("BILL-", 12345, 4)).toBe("BILL-12345");
      expect(formatBillNumber("BILL-", 999999, 4)).toBe("BILL-999999");
    });

    it("supports custom prefixes and custom padding sizes", () => {
      expect(formatBillNumber("VB-", 7, 5)).toBe("VB-00007");
      expect(formatBillNumber("PURCHASE-", 101, 6)).toBe("PURCHASE-000101");
      expect(formatBillNumber("", 15, 3)).toBe("015");
    });

    it("handles boundary values safely (0, negative, undefined)", () => {
      expect(formatBillNumber("BILL-", 0, 4)).toBe("BILL-0001");
      expect(formatBillNumber("BILL-", -10, 4)).toBe("BILL-0001");
    });
  });

  describe("extractBillNumberPart", () => {
    it("extracts the numeric sequence from valid auto-generated bill numbers", () => {
      expect(extractBillNumberPart("BILL-0001", "BILL-")).toBe(1);
      expect(extractBillNumberPart("BILL-0002", "BILL-")).toBe(2);
      expect(extractBillNumberPart("BILL-0042", "BILL-")).toBe(42);
      expect(extractBillNumberPart("BILL-0999", "BILL-")).toBe(999);
      expect(extractBillNumberPart("BILL-1000", "BILL-")).toBe(1000);
      expect(extractBillNumberPart("BILL-12345", "BILL-")).toBe(12345);
    });

    it("handles case-insensitive prefixes and trims whitespace", () => {
      expect(extractBillNumberPart("bill-0005", "BILL-")).toBe(5);
      expect(extractBillNumberPart("  BILL-0010  ", "BILL-")).toBe(10);
    });

    it("returns null for non-matching prefixes, manual invoice formats, and invalid suffixes", () => {
      expect(extractBillNumberPart("INV-0001", "BILL-")).toBeNull();
      expect(extractBillNumberPart("PO-0001", "BILL-")).toBeNull();
      expect(extractBillNumberPart("BILL-ABC", "BILL-")).toBeNull();
      expect(extractBillNumberPart("BILL-001A", "BILL-")).toBeNull();
      expect(extractBillNumberPart("BILL-", "BILL-")).toBeNull();
      expect(extractBillNumberPart("", "BILL-")).toBeNull();
    });
  });

  describe("isAutoGeneratedBillNumber", () => {
    it("correctly identifies auto-generated format strings", () => {
      expect(isAutoGeneratedBillNumber("BILL-0001")).toBe(true);
      expect(isAutoGeneratedBillNumber("BILL-0002")).toBe(true);
      expect(isAutoGeneratedBillNumber("BILL-0042")).toBe(true);
      expect(isAutoGeneratedBillNumber("bill-0100")).toBe(true);
    });

    it("correctly identifies custom/vendor-supplied invoice numbers", () => {
      expect(isAutoGeneratedBillNumber("INV-2026-001")).toBe(false);
      expect(isAutoGeneratedBillNumber("TAX-INV-999")).toBe(false);
      expect(isAutoGeneratedBillNumber("BILL-XYZ")).toBe(false);
      expect(isAutoGeneratedBillNumber("VEND-456")).toBe(false);
      expect(isAutoGeneratedBillNumber("")).toBe(false);
    });
  });

  describe("parseNextBillNumberInput", () => {
    it("parses user input strings and preserves intended padding", () => {
      expect(parseNextBillNumberInput("0002")).toEqual({
        nextNumber: 2,
        padding: 4,
        formattedString: "0002",
      });
      expect(parseNextBillNumberInput("00005")).toEqual({
        nextNumber: 5,
        padding: 5,
        formattedString: "00005",
      });
      expect(parseNextBillNumberInput("10")).toEqual({
        nextNumber: 10,
        padding: 2,
        formattedString: "10",
      });
    });

    it("handles fallback on empty or non-digit input", () => {
      expect(parseNextBillNumberInput("")).toEqual({
        nextNumber: 1,
        padding: 4,
        formattedString: "0001",
      });
      expect(parseNextBillNumberInput("abc")).toEqual({
        nextNumber: 1,
        padding: 4,
        formattedString: "0001",
      });
    });
  });

  describe("findNextAvailableBillNumber (Collision Avoidance)", () => {
    it("returns candidate startingNumber when existing set is empty", () => {
      const existing = new Set<string>();
      const result = findNextAvailableBillNumber("BILL-", 1, 4, existing);
      expect(result).toEqual({
        billNumber: "BILL-0001",
        allocatedNumber: 1,
      });
    });

    it("skips existing bill numbers to guarantee uniqueness", () => {
      const existing = new Set<string>(["BILL-0001", "BILL-0002", "BILL-0003"]);
      const result = findNextAvailableBillNumber("BILL-", 1, 4, existing);
      expect(result).toEqual({
        billNumber: "BILL-0004",
        allocatedNumber: 4,
      });
    });

    it("is case-insensitive when detecting collisions", () => {
      const existing = new Set<string>(["bill-0001", "Bill-0002"]);
      const result = findNextAvailableBillNumber("BILL-", 1, 4, existing);
      expect(result).toEqual({
        billNumber: "BILL-0003",
        allocatedNumber: 3,
      });
    });

    it("fills sequence gaps if candidate starts before an existing number", () => {
      // Gap: 1 exists, 3 exists, 2 is free
      const existing = new Set<string>(["BILL-0001", "BILL-0003"]);
      const result = findNextAvailableBillNumber("BILL-", 1, 4, existing);
      expect(result).toEqual({
        billNumber: "BILL-0002",
        allocatedNumber: 2,
      });
    });

    it("starts from higher candidate without resetting", () => {
      const existing = new Set<string>(["BILL-0001", "BILL-0042"]);
      const result = findNextAvailableBillNumber("BILL-", 42, 4, existing);
      expect(result).toEqual({
        billNumber: "BILL-0043",
        allocatedNumber: 43,
      });
    });
  });

  describe("escapeRegex", () => {
    it("properly escapes regex special characters", () => {
      expect(escapeRegex("BILL-0001 (COPY)")).toBe("BILL\\-0001\\ \\(COPY\\)");
      expect(escapeRegex("INV.2026/01+A")).toBe("INV\\.2026/01\\+A");
      expect(escapeRegex("[TEST]")).toBe("\\[TEST\\]");
    });
  });
});
